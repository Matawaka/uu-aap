#!/usr/bin/env python3
"""Deterministic institution/rule evolution for UU Society v0.6.

Institutions modify the environment of the v0.5 strategy-evolution simulator.
Rule adoption is evaluated from aggregate outcome vectors, never person scores.

The rights floor used here is an experimental proxy, not a complete theory of
human rights.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import itertools
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

from run_scenarios import current_commit, digest, format_errors, load_json, validator
from run_strategy_evolution import simulate as simulate_strategy

ROOT = Path(__file__).resolve().parents[1]
CONFIG_SCHEMA_PATH = ROOT / "institution-evolution.config.schema.json"
RECEIPT_SCHEMA_PATH = ROOT / "institution-evolution.receipt.schema.json"
EXPERIMENT_DIR = ROOT / "institution_evolution"

RULE_VALUES = {
    "evidence_policy": ["private_only", "strategy_outcome"],
    "containment": ["weak", "balanced", "strong"],
    "repair_support": ["none", "basic", "strong"],
    "coalition_policy": ["anti_capture", "neutral", "preferential"],
    "review_path": ["none", "periodic", "independent"],
}
RULE_AXES = tuple(RULE_VALUES)


def rule_key(rules: dict[str, str]) -> str:
    return "|".join(f"{axis}={rules[axis]}" for axis in RULE_AXES)


def ordinal(axis: str, value: str) -> int:
    return RULE_VALUES[axis].index(value)


def one_step_neighbors(rules: dict[str, str]) -> list[dict[str, str]]:
    out = []
    for axis in RULE_AXES:
        values = RULE_VALUES[axis]
        idx = values.index(rules[axis])
        for delta in (-1, 1):
            nxt = idx + delta
            if 0 <= nxt < len(values):
                candidate = dict(rules)
                candidate[axis] = values[nxt]
                out.append(candidate)
    return sorted(out, key=rule_key)


def restrictive_change(current: dict[str, str], candidate: dict[str, str]) -> bool:
    if ordinal("containment", candidate["containment"]) > ordinal("containment", current["containment"]):
        return True
    if (
        candidate["coalition_policy"] == "anti_capture"
        and current["coalition_policy"] != "anti_capture"
    ):
        return True
    return False


def apply_rules(base: dict[str, Any], rules: dict[str, str], seed: str, interactions: int) -> dict[str, Any]:
    cfg = copy.deepcopy(base)
    cfg["experiment_id"] = "E99-institution-probe"
    cfg["experiment_version"] = "0.5"
    cfg["title_en"] = "Institution probe"
    cfg["title_ru"] = "Проба института"
    cfg["purpose"] = "Generated by institution evolution v0.6."
    cfg["seed"] = seed
    cfg["interaction_count"] = interactions
    cfg.setdefault("epoch_count", 12)
    cfg["expected"] = {"result":"PASS","expected_pattern_ids":[]}

    evidence_rate = 0.0 if rules["evidence_policy"] == "private_only" else 0.30
    cfg["learning"]["strategy_evidence_learning_rate"] = evidence_rate

    containment = rules["containment"]
    if containment == "balanced":
        cfg["strategy_parameters"]["EXTRACT"]["harm_rate"] *= 0.65
        cfg["strategy_parameters"]["EXTRACT"]["breach_rate"] *= 0.65
        for strategy in cfg["strategy_parameters"].values():
            strategy["provider_willingness_multiplier"] *= 0.92
    elif containment == "strong":
        cfg["strategy_parameters"]["EXTRACT"]["harm_rate"] *= 0.35
        cfg["strategy_parameters"]["EXTRACT"]["breach_rate"] *= 0.35
        for strategy in cfg["strategy_parameters"].values():
            strategy["provider_willingness_multiplier"] *= 0.68

    support = rules["repair_support"]
    if support == "none":
        cfg["economics"]["repair_reward"] *= 0.20
        cfg["strategy_parameters"]["REPAIR"]["repair_probability"] *= 0.45
    elif support == "strong":
        cfg["economics"]["repair_reward"] *= 2.5
        cfg["economics"]["repair_cost"] *= 0.60
        cfg["strategy_parameters"]["REPAIR"]["repair_probability"] = min(
            1.0, cfg["strategy_parameters"]["REPAIR"]["repair_probability"] * 1.08
        )

    coalition = rules["coalition_policy"]
    if coalition == "preferential":
        cfg["economics"]["coalition_internal_bonus"] *= 2.5
        cfg["economics"]["coalition_maintenance_cost"] *= 0.35
        cfg["strategy_parameters"]["COALITION"]["request_activity"] *= 1.20
        cfg["strategy_parameters"]["COALITION"]["provider_willingness_multiplier"] *= 1.15
    elif coalition == "anti_capture":
        cfg["economics"]["coalition_internal_bonus"] *= 0.30
        cfg["economics"]["coalition_maintenance_cost"] *= 1.35
        cfg["strategy_parameters"]["COALITION"]["request_activity"] *= 0.80
        cfg["strategy_parameters"]["COALITION"]["provider_willingness_multiplier"] *= 0.85

    return cfg


def outcome(receipt: dict[str, Any]) -> dict[str, float]:
    m = receipt["metrics"]
    shares = m["tail_strategy_shares"]
    return {
        "unfulfilled": 1.0 - m["tail_fulfilled_rate"],
        "harm": m["tail_harm_rate"],
        "access_gini": m["access_gini"],
        "provision_gini": m["provision_gini"],
        "exit_share": shares["EXIT"],
        "coalition_share": shares["COALITION"],
        "outsider_gap": m["max_coalition_outsider_gap"],
        "mean_reward": m["mean_total_reward"],
    }


def rights_floor_ok(config: dict[str, Any], o: dict[str, float]) -> bool:
    floor = config["rights_floor_proxy"]
    return (
        1.0 - o["unfulfilled"] >= floor["min_tail_fulfillment"]
        and o["exit_share"] <= floor["max_exit_share"]
        and o["access_gini"] <= floor["max_access_gini"]
        and o["outsider_gap"] <= floor["max_coalition_outsider_gap"]
    )


LOSS_KEYS = ("unfulfilled", "harm", "access_gini", "provision_gini", "exit_share", "outsider_gap")


def pareto_dominates(config: dict[str, Any], candidate: dict[str, float], current: dict[str, float]) -> bool:
    tolerance = config["adoption"]["pareto_tolerance"]
    improvement = config["adoption"]["min_improvement"]
    no_material_worse = all(
        candidate[key] <= current[key] + tolerance for key in LOSS_KEYS
    )
    materially_better = any(
        candidate[key] <= current[key] - improvement for key in LOSS_KEYS
    )
    return no_material_worse and materially_better


def evaluate_bundle(
    config: dict[str, Any],
    rules: dict[str, str],
    cycle: int,
    role: str,
) -> tuple[dict[str, Any], dict[str, float]]:
    # Every institutional alternative in the same governance cycle must face
    # the same deterministic event tape. Otherwise random differences can be
    # mistaken for policy effects (e.g. a review-path-only change appearing to
    # improve population outcomes).
    seed = f"{config['seed']}|cycle={cycle}"
    probe = apply_rules(
        config["base_strategy_environment"],
        rules,
        seed,
        config["evaluation_interactions"],
    )
    receipt, _errors = simulate_strategy(probe, enforce_expected=False)
    return receipt, outcome(receipt)


def choose_candidate(
    config: dict[str, Any],
    current_rules: dict[str, str],
    current_outcome: dict[str, float],
    evaluations: list[tuple[dict[str, str], dict[str, float]]],
    rejection_counts: Counter[str],
) -> tuple[dict[str, str] | None, dict[str, float] | None, str]:
    mode = config["governance_mode"]

    if mode == "frozen":
        return None, None, "frozen"

    if mode == "pareto_rights_floor":
        for rules, o in evaluations:
            if not rights_floor_ok(config, o):
                rejection_counts["rights_floor"] += 1
                continue
            if restrictive_change(current_rules, rules) and rules["review_path"] == "none":
                rejection_counts["review_gate"] += 1
                continue
            if pareto_dominates(config, o, current_outcome):
                return rules, o, "pareto_rights_floor"
            rejection_counts["not_pareto"] += 1
        return None, None, "no_eligible_neighbor"

    if mode == "harm_only":
        threshold = config["adoption"]["harm_only_min_improvement"]
        ordered = sorted(evaluations, key=lambda item: (item[1]["harm"], rule_key(item[0])))
        rules, o = ordered[0]
        if o["harm"] <= current_outcome["harm"] - threshold:
            return rules, o, "harm_only"
        rejection_counts["harm_not_improved"] += 1
        return None, None, "no_harm_improvement"

    if mode == "self_ratifying_coalition":
        threshold = config["adoption"]["self_ratification_min_coalition_gain"]
        ordered = sorted(
            evaluations,
            key=lambda item: (-item[1]["coalition_share"], rule_key(item[0])),
        )
        rules, o = ordered[0]
        if o["coalition_share"] >= current_outcome["coalition_share"] + threshold:
            return rules, o, "coalition_self_interest"
        rejection_counts["coalition_gain_too_small"] += 1
        return None, None, "no_coalition_gain"

    raise ValueError(f"unknown governance mode {mode}")


def simulate(config: dict[str, Any], enforce_expected: bool = True) -> tuple[dict[str, Any], list[str]]:
    current_rules = dict(config["initial_rules"])
    rejection_counts: Counter[str] = Counter()
    trace = hashlib.sha256()
    cycles = []
    adoption_count = 0
    ever_adopted = set()
    saw_rights_block = False
    saw_review_block = False
    saw_self_ratification = False
    initial_containment = ordinal("containment", current_rules["containment"])

    for cycle in range(config["cycle_count"]):
        _current_receipt, current_o = evaluate_bundle(
            config, current_rules, cycle, "incumbent"
        )

        neighbors = one_step_neighbors(current_rules)
        evaluations = []
        if config["governance_mode"] != "frozen":
            for rules in neighbors:
                _receipt, o = evaluate_bundle(config, rules, cycle, "candidate")
                evaluations.append((rules, o))

        before_counts = dict(rejection_counts)
        candidate, candidate_o, reason = choose_candidate(
            config, current_rules, current_o, evaluations, rejection_counts
        )
        saw_rights_block |= rejection_counts["rights_floor"] > before_counts.get("rights_floor", 0)
        saw_review_block |= rejection_counts["review_gate"] > before_counts.get("review_gate", 0)

        adopted = candidate is not None
        previous_rules = dict(current_rules)
        if adopted:
            current_rules = dict(candidate)
            adoption_count += 1
            for axis in RULE_AXES:
                if current_rules[axis] != previous_rules[axis]:
                    ever_adopted.add((axis, current_rules[axis]))
            if config["governance_mode"] == "self_ratifying_coalition":
                saw_self_ratification = True

        final_o = candidate_o if adopted else current_o
        cycles.append({
            "cycle":cycle,
            "rules_before":previous_rules,
            "outcome_before":current_o,
            "adopted":adopted,
            "adoption_reason":reason,
            "rules_after":dict(current_rules),
            "outcome_after":final_o,
            "rights_floor_after":rights_floor_ok(config, final_o),
        })
        trace.update(
            (
                f"{cycle}|before={rule_key(previous_rules)}|adopted={int(adopted)}|"
                f"after={rule_key(current_rules)}|reason={reason}|"
                f"outcome={json.dumps(final_o,sort_keys=True)}\n"
            ).encode()
        )

    # Final confirmation run uses a fresh deterministic role tag.
    _final_receipt, final_o = evaluate_bundle(
        config, current_rules, config["cycle_count"], "final"
    )

    patterns = set()
    if adoption_count > 0:
        patterns.add("INSTITUTIONAL_ADAPTATION")
    else:
        patterns.add("STABLE_RULE_BUNDLE")
    if ("evidence_policy", "strategy_outcome") in ever_adopted:
        patterns.add("EVIDENCE_POLICY_ADOPTED")
    if ("repair_support", "strong") in ever_adopted:
        patterns.add("REPAIR_SUPPORT_ADOPTED")
    if saw_rights_block:
        patterns.add("RIGHTS_FLOOR_BLOCKED_RULE")
    if saw_review_block:
        patterns.add("REVIEW_GATE_BLOCKED_RULE")
    if (
        ordinal("containment", current_rules["containment"]) > initial_containment
        and current_rules["review_path"] == "none"
        and (
            not rights_floor_ok(config, final_o)
            or final_o["exit_share"] > config["rights_floor_proxy"]["max_exit_share"]
        )
    ):
        patterns.add("RESTRICTION_RATCHET")
    if saw_self_ratification:
        patterns.add("SELF_RATIFYING_RULE_ADOPTION")
    if ("coalition_policy", "preferential") in ever_adopted:
        patterns.add("COALITION_PRIVILEGE_ADOPTED")
    if final_o["exit_share"] > config["rights_floor_proxy"]["max_exit_share"]:
        patterns.add("MASS_EXIT_REGIME")

    actual_result = "EXPECTED_DETECTION" if patterns else "PASS"
    errors = []
    if enforce_expected:
        expected = set(config["expected"]["expected_pattern_ids"])
        if actual_result != config["expected"]["result"]:
            errors.append(
                f"result expected={config['expected']['result']} actual={actual_result}"
            )
        if patterns != expected:
            errors.append(
                f"patterns expected={sorted(expected)} actual={sorted(patterns)}"
            )

    receipt = {
        "receipt_version":"0.6",
        "experiment_id":config["experiment_id"],
        "experiment_version":"0.6",
        "model_commit_sha":current_commit(),
        "seed":config["seed"],
        "governance_mode":config["governance_mode"],
        "result":actual_result if not errors else "FAIL",
        "pattern_ids":sorted(patterns),
        "final_rules":current_rules,
        "cycle_summaries":cycles,
        "adoption_count":adoption_count,
        "rejection_counts":dict(sorted(rejection_counts.items())),
        "trace_digest":trace.hexdigest(),
        "config_digest":digest(config),
    }
    return receipt, errors


def run_config(path: Path) -> tuple[dict[str, Any], list[str]]:
    config = load_json(path)
    config_errors = format_errors(
        validator(load_json(CONFIG_SCHEMA_PATH)).iter_errors(config)
    )
    if config_errors:
        return {}, [f"config schema: {e}" for e in config_errors]
    receipt, errors = simulate(config)
    receipt_errors = format_errors(
        validator(load_json(RECEIPT_SCHEMA_PATH)).iter_errors(receipt)
    )
    return receipt, [*errors, *[f"receipt schema: {e}" for e in receipt_errors]]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--experiment", action="append")
    args = parser.parse_args()
    paths = sorted(EXPERIMENT_DIR.glob("G*/config.json"))
    if args.experiment:
        wanted = set(args.experiment)
        paths = [p for p in paths if load_json(p)["experiment_id"] in wanted]
    if not paths:
        print("no institution evolution experiments found", file=sys.stderr)
        return 2

    failures = []
    receipts = []
    for path in paths:
        receipt, errors = run_config(path)
        eid = load_json(path)["experiment_id"]
        if errors:
            print(f"{eid}: FAIL")
            if receipt:
                print("  final_rules:", json.dumps(receipt["final_rules"], sort_keys=True))
                print("  patterns:", ",".join(receipt["pattern_ids"]) or "<none>")
                print("  adoptions:", receipt["adoption_count"])
                print("  rejections:", json.dumps(receipt["rejection_counts"], sort_keys=True))
            for error in errors:
                print(f"  - {error}")
            failures.extend(f"{eid}: {e}" for e in errors)
        else:
            print(f"{eid}: {receipt['result']}")
            print("  final_rules:", json.dumps(receipt["final_rules"], sort_keys=True))
            print("  patterns:", ",".join(receipt["pattern_ids"]) or "<none>")
            print("  adoptions:", receipt["adoption_count"])
            print("  rejections:", json.dumps(receipt["rejection_counts"], sort_keys=True))
            print("  trace_digest:", receipt["trace_digest"])
            receipts.append(receipt)

    print(
        f"\nUU Society institution evolution v0.6: "
        f"{len(receipts)}/{len(paths)} experiments conform"
    )
    if failures:
        print(f"unexpected failures: {len(failures)}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
